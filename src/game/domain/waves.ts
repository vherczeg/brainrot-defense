export function getWave(waveId: number): WaveDefinition | null {
  return WAVE_DEFINITIONS.find((wave) => wave.id === waveId) ?? null;
}

export function getWaveForProfile(profileId: string, waveId: number): WaveDefinition | null {
  const wave = getWave(waveId);
  if (!wave) return null;
  return buildSurpriseBossWave(profileId, wave)?.wave ?? wave;
}

export const WAVE_REPLAY_REWARD_PERCENT = 35;

export function waveRewardCoins(wave: WaveDefinition): number {
  return scaledWaveRewardCoins(wave.rewardCoins, wave.modifier);
}

export function waveReplayRewardCoins(wave: WaveDefinition): number {
  return Math.floor((waveRewardCoins(wave) * WAVE_REPLAY_REWARD_PERCENT) / 100);
}

export function waveFirstCompletionBonus(wave: WaveDefinition): number {
  return waveRewardCoins(wave) - waveReplayRewardCoins(wave);
}

export const FIRST_WAVE_ID = 1;
export const LAST_WAVE_ID = TOTAL_WAVES;

export function isValidWaveId(waveId: number): boolean {
  return Number.isInteger(waveId) && getWave(waveId) !== null;
}

export function isValidEnemyPosition(col: number, row: number): boolean {
  return (
    Number.isInteger(col) &&
    Number.isInteger(row) &&
    col >= 0 &&
    col < BOARD_COLS &&
    row >= 0 &&
    row < ALLY_ROW_START
  );
}
