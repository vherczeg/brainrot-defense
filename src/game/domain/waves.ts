function enemy(typeId: EnemyTypeId, level: number, col: number, row: number): WaveEnemyConfig {
  return { typeId, level, col, row };
}

interface NormalWaveOptions {
  readonly modifier?: WaveModifierId;
  readonly reward?: number;
}

function normalWave(
  id: number,
  nameHu: string,
  descriptionHu: string,
  enemies: readonly WaveEnemyConfig[],
  options: NormalWaveOptions = {},
): WaveDefinition {
  return {
    id,
    nameHu,
    descriptionHu,
    rewardCoins: options.reward ?? defaultWaveReward(id),
    isBossWave: false,
    chapterId: chapterOf(id),
    ...(options.modifier ? { modifier: options.modifier } : {}),
    enemies,
  };
}

function bossWave(
  id: number,
  nameHu: string,
  descriptionHu: string,
  enemies: readonly WaveEnemyConfig[],
  reward?: number,
  modifier?: WaveModifierId,
): WaveDefinition {
  return {
    id,
    nameHu,
    descriptionHu,
    rewardCoins: reward ?? defaultWaveReward(id),
    isBossWave: true,
    chapterId: chapterOf(id),
    ...(modifier ? { modifier } : {}),
    enemies,
  };
}

function chapterOf(waveId: number): number {
  return Math.floor((waveId - 1) / 10) + 1;
}

function defaultWaveReward(waveId: number): number {
  if (waveId < 21) return 0;
  const base = 850 + 25 * (waveId - 21);
  if (waveId === 100) return 5000;
  if (waveId % 10 === 0) return Math.round(base * 1.45);
  return base;
}

